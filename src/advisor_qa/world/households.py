"""Sample households from the SCF pool and turn their dollars into accounts and holdings.

Everything here is seeded: the same seed, pool and parameters give identical tables.
SCF gives category dollars only. Which funds, how many, ETF vs mutual fund, advisors and IDs are
generated by us (see docs in `config/default.yaml` and `instruments.csv`).
"""

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from advisor_qa.world import fixture as fx
from advisor_qa.world.instruments import Candidates, pool_candidates, target_date_id
from advisor_qa.world.params import HouseholdParams

TAXABLE, IRA, TRUST, HELD_AWAY = "taxable", "ira", "trust", "401k_held_away"
FIRST_ACCOUNT_NUMBER = 10_001


@dataclass
class WorldTables:
    households: pd.DataFrame
    accounts: pd.DataFrame
    holdings: pd.DataFrame
    instruments: pd.DataFrame

    def write(self, out_dir: Path) -> None:
        out_dir.mkdir(parents=True, exist_ok=True)
        for name in ("households", "accounts", "holdings", "instruments"):
            frame: pd.DataFrame = getattr(self, name)
            frame.to_csv(out_dir / f"{name}.csv", index=False)


def draw_records(
    pool: pd.DataFrame, n: int, rng: np.random.Generator, unique_families: bool
) -> pd.DataFrame:
    """Draw n records with probability proportional to WGT.

    With unique_families, a family never appears twice (weighted sampling without replacement via
    Efraimidis-Spirakis keys), so the sample drifts from the weighted population as n approaches the
    number of eligible families.
    """
    w = pool["WGT"].to_numpy(dtype=float)
    if not unique_families:
        return pool.iloc[rng.choice(len(pool), size=n, p=w / w.sum())].reset_index(drop=True)
    if n > pool["YY1"].nunique():
        raise ValueError(f"asked for {n} households but only {pool['YY1'].nunique()} families")
    order = np.argsort(-(np.log(rng.random(len(pool))) / w))
    seen: set[int] = set()
    chosen: list[int] = []
    for i in order:
        fam = int(pool["YY1"].iloc[i])
        if fam not in seen:
            seen.add(fam)
            chosen.append(int(i))
            if len(chosen) == n:
                break
    return pool.iloc[chosen].reset_index(drop=True)


def _split(
    dollars: float,
    cands: Candidates,
    rng: np.random.Generator,
    etf_share: float,
    min_holding: float,
) -> list[tuple[str, float]]:
    """Split a pool over 1-2 instruments; each slot is an ETF with probability etf_share."""
    k = 2 if (dollars >= 2 * min_holding and rng.random() < 0.5) else 1
    chosen: list[str] = []
    for _ in range(k):
        group = cands.etf if rng.random() < etf_share else cands.mf
        group = group or (cands.mf or cands.etf)
        options = [i for i in group if i not in chosen] or list(group)
        chosen.append(options[int(rng.integers(len(options)))])
    chosen = list(dict.fromkeys(chosen))
    amounts = rng.dirichlet(np.ones(len(chosen))) * dollars
    if len(chosen) > 1 and amounts.min() < min_holding:
        return [(chosen[0], dollars)]
    return list(zip(chosen, (float(a) for a in amounts), strict=True))


def _retirement_pools(bal: float, eq_ratio: float, tdf_share: float) -> dict[str, float]:
    rest = bal * (1 - tdf_share)
    return {"tdf": bal * tdf_share, "equity": rest * eq_ratio, "bond": rest * (1 - eq_ratio)}


def _account_pools(
    row: pd.Series, p: HouseholdParams, rng: np.random.Generator
) -> dict[str, dict[str, float]]:
    """Account type -> pool name -> dollars, for one SCF record."""
    r = row
    eq_ratio = float(r["RETEQ"] / r["RETQLIQ"]) if r["RETQLIQ"] > 0 else 0.5
    taxable = {
        "equity": r["STOCKS"] + r["STMUTF"] + r["OMUTF"],
        "bond": r["GBMUTF"] + r["OBMUTF"] + r["BOND"],
        "muni": r["TFBMUTF"],
        "short": r["CDS"],
        "tdf": r["COMUTF"],
        "cash": r["LIQ"],
    }
    # Always draw, so the random stream does not depend on the data.
    is_spec, frac = (
        rng.random() < p.speculative_household_rate,
        rng.uniform(0.01, p.speculative_max_equity_share),
    )
    if is_spec and taxable["equity"] > 0:
        taxable["spec"] = frac * taxable["equity"]
        taxable["equity"] -= taxable["spec"]
    out = {
        TAXABLE: taxable,
        IRA: _retirement_pools(r["IRAKH"], eq_ratio, p.target_date_share_of_retirement),
        HELD_AWAY: _retirement_pools(r["THRIFT"], eq_ratio, p.target_date_share_of_retirement),
        TRUST: {
            "equity": r["TRUSTS"] * p.trust_equity_share,
            "bond": r["TRUSTS"] * (1 - p.trust_equity_share),
        },
    }
    return {t: {k: float(v) for k, v in pools.items() if v > 0} for t, pools in out.items()}


def _merge_small(pools: dict[str, float], min_holding: float) -> dict[str, float]:
    if not pools:
        return pools
    big = max(pools, key=lambda k: pools[k])
    out = {k: v for k, v in pools.items() if v >= min_holding or k == big}
    out[big] += sum(v for k, v in pools.items() if k not in out)
    return out


def _household_rows(
    row: pd.Series, p: HouseholdParams, inst: pd.DataFrame, rng: np.random.Generator
) -> list[tuple[str, dict[str, float]]]:
    """(account type, instrument_id -> dollars) for each non-empty account."""
    cands = pool_candidates(inst)
    result: list[tuple[str, dict[str, float]]] = []
    for acct_type, pools in _account_pools(row, p, rng).items():
        pools = _merge_small(pools, p.min_holding_value)
        by_instrument: dict[str, float] = {}
        mf_only = acct_type == HELD_AWAY and p.held_away_mutual_funds_only
        etf_share = 0.0 if mf_only else p.etf_share_of_fund_dollars
        for pool, dollars in pools.items():
            c = (
                Candidates((), (target_date_id(inst, float(row["AGE"])),))
                if pool == "tdf"
                else cands[pool]
            )
            for ins, amt in _split(dollars, c, rng, etf_share, p.min_holding_value):
                by_instrument[ins] = by_instrument.get(ins, 0.0) + amt
        if by_instrument:
            result.append((acct_type, by_instrument))
    return result


def _fixed_ids(n: int, reserved: str, prefix: str, width: int) -> list[str]:
    out: list[str] = []
    i = 1
    while len(out) < n:
        cand = f"{prefix}{i:0{width}d}"
        if cand != reserved:
            out.append(cand)
        i += 1
    return out


def _qty_value(dollars: float, price: float) -> tuple[float, float]:
    qty = round(dollars / price, 4)
    return qty, round(qty * price, 2)


def fixture_tables(inst: pd.DataFrame) -> WorldTables:
    prices = inst.set_index("instrument_id")["reference_price"]
    hold = pd.DataFrame(
        [
            {
                "household_id": fx.FIXTURE_HOUSEHOLD_ID,
                "account_id": a,
                "instrument_id": i,
                "qty": q,
                "value_usd": round(q * float(prices[i]), 2),
            }
            for a, i, q in fx.FIXTURE_HOLDINGS
        ]
    )
    acc = pd.DataFrame(
        [
            {
                "account_id": a,
                "household_id": fx.FIXTURE_HOUSEHOLD_ID,
                "type": t,
                "in_crm": True,
                "held_away": t == HELD_AWAY,
            }
            for a, t in fx.FIXTURE_ACCOUNTS
        ]
    )
    total = round(float(hold["value_usd"].sum()), 2)
    hh = pd.DataFrame(
        [
            {
                "household_id": fx.FIXTURE_HOUSEHOLD_ID,
                "advisor_id": fx.FIXTURE_ADVISOR_ID,
                "scf_weight": np.nan,
                "total_value": total,
                "age": float(fx.FIXTURE_AGE),
                "scf_y1": pd.NA,
                "scf_fin": np.nan,
                "scf_modelled_value": total,
                "is_fixture": True,
            }
        ]
    )
    return WorldTables(hh, acc, hold, inst)


def generate_world(
    pool: pd.DataFrame, inst: pd.DataFrame, p: HouseholdParams, n: int, seed: int
) -> WorldTables:
    """n households in total: the hand-built fixture plus n-1 sampled from the pool."""
    fixture = fixture_tables(inst)
    records = draw_records(pool, n - 1, np.random.default_rng([seed, 1]), p.unique_families)

    adv_rng = np.random.default_rng([seed, 2])
    adv_numbers = [x for x in range(1, 1000) if f"ADV-{x:04d}" != fx.FIXTURE_ADVISOR_ID]
    picked = adv_rng.choice(adv_numbers, size=p.n_advisors - 1, replace=False)
    advisors = sorted([f"ADV-{int(x):04d}" for x in picked] + [fx.FIXTURE_ADVISOR_ID])

    prices = inst.set_index("instrument_id")["reference_price"].astype(float)
    hh_ids = _fixed_ids(len(records), fx.FIXTURE_HOUSEHOLD_ID, "HH-", 6)
    next_acc = FIRST_ACCOUNT_NUMBER
    hh_rows: list[dict[str, object]] = []
    acc_rows: list[dict[str, object]] = []
    hold_rows: list[dict[str, object]] = []
    for idx, (_, rec) in enumerate(records.iterrows()):
        hh_id = hh_ids[idx]
        rng = np.random.default_rng([seed, 3, idx])
        advisor = advisors[int(rng.integers(len(advisors)))]
        total = 0.0
        for acct_type, dollars_by_ins in _household_rows(rec, p, inst, rng):
            while f"ACC-{next_acc:05d}" in fx.FIXTURE_ACCOUNT_IDS:
                next_acc += 1
            acc_id = f"ACC-{next_acc:05d}"
            next_acc += 1
            held_away = acct_type == HELD_AWAY
            in_crm = not (held_away and rng.random() < p.held_away_not_in_crm_rate)
            acc_rows.append(
                {
                    "account_id": acc_id,
                    "household_id": hh_id,
                    "type": acct_type,
                    "in_crm": in_crm,
                    "held_away": held_away,
                }
            )
            for ins, dollars in dollars_by_ins.items():
                qty, value = _qty_value(dollars, float(prices[ins]))
                total += value
                hold_rows.append(
                    {
                        "household_id": hh_id,
                        "account_id": acc_id,
                        "instrument_id": ins,
                        "qty": qty,
                        "value_usd": value,
                    }
                )
        hh_rows.append(
            {
                "household_id": hh_id,
                "advisor_id": advisor,
                "scf_weight": float(rec["WGT"]),
                "total_value": round(total, 2),
                "age": float(rec["AGE"]),
                "scf_y1": int(rec["Y1"]),
                "scf_fin": float(rec["FIN"]),
                "scf_modelled_value": float(rec["modelled_value"]),
                "is_fixture": False,
            }
        )
    sampled = WorldTables(
        pd.DataFrame(hh_rows), pd.DataFrame(acc_rows), pd.DataFrame(hold_rows), inst
    )
    return WorldTables(
        pd.concat([fixture.households, sampled.households], ignore_index=True)
        .sort_values("household_id")
        .reset_index(drop=True),
        pd.concat([fixture.accounts, sampled.accounts], ignore_index=True),
        pd.concat([fixture.holdings, sampled.holdings], ignore_index=True),
        inst,
    )
